import { test, expect } from '@playwright/test';
import { chooseSelect2 } from './select2-helper';
import { writeFile } from 'node:fs/promises';

test('simple registration, reviewed schedule, discount, full receipt, attendance and shared A4 print',async({page},info)=>{
  await page.goto('/login');
  await page.getByLabel('نام کاربری',{exact:true}).fill('e2e-admin');
  await page.getByLabel('رمز عبور',{exact:true}).fill(process.env['E2E_PASSWORD']!);
  await page.getByRole('button',{name:'ورود',exact:true}).click();
  await expect(page.getByRole('heading',{name:'کارهای امروز',exact:true})).toBeVisible();
  const auth=await(await page.request.get('/api/auth/me')).json();
  const headers={Origin:'http://localhost:4310','X-CSRF-Token':auth.csrf};
  const add=async(path:string,data:unknown)=>{const r=await page.request.post('/api'+path,{headers,data});expect(r.status(),await r.text()).toBe(201);return r.json();};
  const suffix=info.project.name;
  const instrument=await add('/base-data/instruments',{name:'پیانو مسیر ساده '+suffix,rateToman30:'500000',rateUsd30:'25.50'});
  const teacher=await add('/base-data/instructors',{firstName:'شهرام',lastName:'محذوف',instrumentIds:[instrument.id]});
  const delivery=await add('/base-data/teaching-types',{name:'حضوری ساده '+suffix,requiresAcademy:true});
  const academy=await add('/subject-catalog',{name:'آموزشگاه ساده '+suffix});
  const policies=await(await page.request.get('/api/registration-policies')).json();
  const draft=policies.items.find((p:any)=>p.status==='draft');
  if(draft){expect((await page.request.patch('/api/registration-policies/'+draft.id,{headers,data:{title:draft.title,contentHtml:draft.content_html,effectiveOn:'2026-01-01'}})).status()).toBe(200);expect((await page.request.post('/api/registration-policies/'+draft.id+'/publish',{headers,data:{}})).status()).toBe(200);}
  await page.goto('/students/new');
  await page.locator('#first').fill('هنرجوی');await page.locator('#last').fill('ساده '+suffix);await page.locator('#phone').fill('۰۹۱۲۱۲۳۴۵۶۷');
  await page.screenshot({path:`docs/evidence/${suffix}-simple-registration.png`,fullPage:true});
  await page.getByRole('button',{name:'ذخیره و چاپ پرونده',exact:true}).click();
  await expect(page).toHaveURL(/\/students\/\d+\/print$/);
  await expect(page.locator('.student-print-sheet')).toContainText('هنرجوی ساده '+suffix);
  const id=Number(new URL(page.url()).pathname.split('/')[2]);
  const read=async()=> (await page.request.get('/api/students/'+id)).json();
  expect((await read()).terms).toHaveLength(0);
  await page.goto('/students/'+id);
  await page.getByRole('button',{name:'ترم جدید',exact:true}).first().click();
  await expect(page.locator(`#education-instrument option[value="${instrument.id}"]`)).toHaveCount(1);
  await chooseSelect2(page,'ساز *',String(instrument.id));
  await expect(page.locator('#education-instructor')).toHaveValue(String(teacher.id));
  await chooseSelect2(page,'شیوه برگزاری *',String(delivery.id));
  await chooseSelect2(page,'آموزشگاه *',String(academy.id));
  const form=page.locator('app-term-form');
  await form.getByRole('button',{name:'ادامه',exact:true}).click();
  await page.locator('#duration').fill('45');await page.locator('#start').fill('1405/07/01');
  await form.getByRole('button',{name:'افزودن نوبت هفتگی'}).click();
  await chooseSelect2(page,'روز هفته','3');
  await page.locator('#schedule-time-0').fill('23:45');await page.locator('#schedule-duration-0').fill('45');
  await expect(form).toContainText('00:30 (روز بعد)');
  await form.getByRole('switch',{name:'این تاریخ‌ها را بازبینی کردم؛ همراه ترم رزرو شوند'}).check();
  await form.getByRole('button',{name:'ادامه',exact:true}).click();
  await expect(page.locator('#base-rate')).toHaveValue('500000');
  await chooseSelect2(page,'نوع تخفیف','fixed');await page.locator('#discount-amount').fill('200000');
  await expect(form).toContainText('۲٬۸۰۰٬۰۰۰');
  await chooseSelect2(page,'نوع تخفیف','percent');await expect(page.locator('#discount-percent')).toHaveValue('');await page.locator('#discount-percent').fill('10');
  await page.locator('#treason').fill('تخفیف مصوب');
  await expect(form).toContainText('۲٬۷۰۰٬۰۰۰');
  await form.getByRole('button',{name:'ادامه',exact:true}).click();
  await form.getByRole('button',{name:'تأیید و ثبت ترم'}).click();
  await expect(form).toHaveCount(0);
  let student=await read(),term=student.terms[0];expect(term.sessions).toHaveLength(4);expect(term.invoice.total_minor).toBe(2700000);
  const first=term.sessions[0];
  await page.getByRole('radio',{name:'غایب جلسه '+first.session_id,exact:true}).first().click();
  const attendance=page.locator('app-attendance-form');await expect(attendance).toContainText('غیبت یک جلسه محسوب می‌شود');
  await attendance.locator('#attendance-reason').fill('عدم حضور هنرجو');await attendance.getByRole('button',{name:'تأیید وضعیت'}).click();
  await expect(attendance).toHaveCount(0);student=await read();expect(student.terms[0].counters.consumed).toBe(1);
  await page.getByRole('button',{name:'ثبت پرداخت',exact:true}).first().click();
  await chooseSelect2(page,'ترم و صورتحساب مقصد *',String(term.id));
  await expect(page.locator('#pay-amount')).toHaveAttribute('readonly','');
  await page.getByRole('button',{name:'ثبت دریافت کامل شهریه',exact:true}).click();
  await expect(page.locator('app-payment-form')).toHaveCount(0);
  student=await read();expect(student.terms[0].invoice.financial_status).toBe('settled');expect(student.payments).toHaveLength(1);
  await page.getByRole('link',{name:'چاپ این ترم',exact:true}).click();await expect(page.locator('.student-print-sheet')).toContainText('۲٬۷۰۰٬۰۰۰');
  await page.screenshot({path:`docs/evidence/${suffix}-registration-print.png`,fullPage:true});
  const pdf=await page.request.get(`/api/students/${id}/registration.pdf?termId=${term.id}`);
  expect(pdf.status(),await pdf.text()).toBe(200);expect(pdf.headers()['content-type']).toContain('application/pdf');
  const bytes=await pdf.body();expect(bytes.subarray(0,5).toString()).toBe('%PDF-');await writeFile(info.outputPath('registration.pdf'),bytes);
  await page.goto('/students');
  const grid=page.locator('app-data-grid');await expect(grid).toBeVisible();
  const action=page.getByRole('link',{name:'چاپ پرونده',exact:true});
  await expect(action.first()).toBeVisible();await action.first().click();await expect(page.locator('.student-print-sheet')).toBeVisible();
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);expect(overflow).toBe(false);
});
